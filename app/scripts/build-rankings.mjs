/**
 * The rankings a build ships with: BenchLM's overall surface, fetched once, validated, and written
 * as the module the app imports (`src/lib/rankings-data.ts`).
 *
 * The score a model shows belongs to a release rather than to a request — `typecheck`, `pnpm dev`
 * and every test read the payload — so nothing here runs at build time on a developer's machine or
 * in CI's gates: this script is run by the weekly BenchLM job (`.github/workflows/benchlm-match.yml`)
 * and by whoever wants a fresher copy, and its output is committed. That is also what makes the
 * reviewed diff the place a score change is seen.
 *
 *   BENCHLM_DATA_KEY=... pnpm build:rankings
 */
import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath, pathToFileURL } from "node:url"

/** The overall surface: the one BenchLM ranks the picker's models on. */
export const BENCHLM_URL = "https://data.benchlm.ai/v1/rankings/current?surface=overall"

/** The surface has ~220 rows and the API caps a page at 100, so a build pages until one is short. */
export const PAGE_SIZE = 100

/** The module the app imports: a TS file, since the tsconfigs resolve no JSON. */
export const DATA = fileURLToPath(new URL("../src/lib/rankings-data.ts", import.meta.url))

/** The fields of a row the app reads: the ids a score is found by, and the score itself. */
const ROW_FIELDS = ["modelKey", "slug", "name", "score"]

/** The envelope fields the app reads; the rest of BenchLM's answer describes a fetch, not a file. */
const ENVELOPE_FIELDS = ["dataAsOf"]

/** The module's opening, which says where the file comes from so a reader never edits it by hand. */
const HEADER = `/**
 * BenchLM's overall rankings, as this build ships them: the rows the model picker scores from.
 *
 * Generated by \`pnpm build:rankings\` (\`scripts/build-rankings.mjs\`) from
 * ${BENCHLM_URL} — refreshed weekly by
 * \`.github/workflows/benchlm-match.yml\`, which commits what it fetched. The copy committed here is
 * what a build without \`BENCHLM_DATA_KEY\` uses, and it is what a reviewer reads. Do not edit it by
 * hand: \`scripts/test-rankings-bake.mjs\` fails on a file this script would not have written.
 */
`

/**
 * A surface the app can score from: an object whose `items` is an array of rows. The envelope's
 * other fields (`dataAsOf`, the surface's own name) ride along unread, so nothing here has to know
 * BenchLM's whole shape.
 */
export function isRankingsPayload(payload) {
  if (typeof payload !== "object" || payload === null || Array.isArray(payload)) return false
  const items = payload.items
  return Array.isArray(items) && items.every((item) => typeof item === "object" && item !== null)
}

function refusal(payload) {
  return new Error(
    `BenchLM answered no rankings: expected an object carrying an items array of rows, got ` +
      `${Array.isArray(payload) ? "an array" : typeof payload}` +
      `${typeof payload === "object" && payload !== null && "items" in payload ? ` whose items is ${typeof payload.items}` : ""}`,
  )
}

/**
 * A page folded onto the payload so far: the first page brings the envelope, every page after it
 * only its rows. A page that is not a surface is refused rather than merged, so a partial answer
 * never reaches the file.
 */
export function mergePage(merged, page) {
  if (!isRankingsPayload(page)) throw refusal(page)
  if (!merged) return { ...page, items: [...page.items] }
  return { ...merged, items: [...merged.items, ...page.items] }
}

/**
 * Every row of the overall surface: pages asked for by offset until one comes back short, the key
 * sent as the bearer token BenchLM wants.
 */
export async function fetchAllRankings({ key, fetchImpl = fetch }) {
  if (!key) throw new Error("BENCHLM_DATA_KEY is not set")
  const headers = { Authorization: `Bearer ${key}` }
  let merged
  let offset = 0
  for (;;) {
    const response = await fetchImpl(`${BENCHLM_URL}&limit=${PAGE_SIZE}&offset=${offset}`, {
      headers,
    })
    if (!response.ok) throw new Error(`BenchLM responded ${response.status}`)
    const page = await response.json()
    merged = mergePage(merged, page)
    if (page.items.length < PAGE_SIZE) return merged
    offset += PAGE_SIZE
  }
}

/** One row, as the module draws it: a line of its own, so a refresh's diff is the models that moved. */
const row = (item) => {
  const kept = Object.fromEntries(
    ROW_FIELDS.filter((name) => item[name] !== undefined).map((name) => [name, item[name]]),
  )
  return `    ${JSON.stringify(kept)},`
}

/** A field as TypeScript writes it: bare where it can be, quoted where it cannot. */
const fieldName = (name) => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name))

/**
 * The module's text: the payload as a typed constant, with the rows one to a line. `items` is
 * written last whatever order the surface carries it in, so the file reads as an envelope and then
 * its models, and only the fields the app reads are written: the rest of BenchLM's answer describes
 * a fetch — a page limit and a next offset, a methodology, the surface's own name — not the file
 * this becomes.
 */
export function moduleText(payload) {
  if (!isRankingsPayload(payload)) throw refusal(payload)
  const envelope = Object.entries(payload)
    .filter(([name]) => ENVELOPE_FIELDS.includes(name))
    .map(([name, value]) => `  ${fieldName(name)}: ${JSON.stringify(value)},`)
  return `${HEADER}
/** One row of BenchLM's overall surface, as the picker reads it. */
export interface RankingRow {
  /** The id BenchLM files the row under: \`modelKey\`, or its slug or name where it carries none. */
  modelKey?: string
  slug?: string
  name?: string
  /** The overall score the picker draws and sorts by. */
  score?: number
}

/** The overall surface as this build ships it. */
export interface RankingsData {
  /** BenchLM's own date for the data, where the surface carries one. */
  dataAsOf?: string
  /** The ranked models. */
  items: RankingRow[]
}

export const RANKINGS: RankingsData = {
${envelope.length ? `${envelope.join("\n")}\n` : ""}  items: [
${payload.items.map(row).join("\n")}
  ],
}
`
}

/**
 * Writes `payload` to `file` (the committed module by default), or throws before touching it: a
 * surface that cannot be scored from leaves the payload the last good answer wrote exactly as it
 * was. Answers the text it wrote and the file's text before it, so a caller can say whether the
 * refresh moved anything.
 */
export function writeRankings(payload, file = DATA) {
  const text = moduleText(payload)
  let previous = null
  try {
    previous = readFileSync(file, "utf8")
  } catch (error) {
    if (error?.code !== "ENOENT") throw error
  }
  writeFileSync(file, text, "utf8")
  return { text, previous }
}

async function main() {
  const key = process.env.BENCHLM_DATA_KEY
  if (!key) {
    console.error("build-rankings: set BENCHLM_DATA_KEY; the committed payload is untouched")
    process.exitCode = 2
    return
  }
  try {
    const payload = await fetchAllRankings({ key })
    const { text, previous } = writeRankings(payload)
    const rows = payload.items.length
    const changed = previous === text ? "unchanged" : "changed"
    console.log(`build-rankings: wrote ${DATA} — ${rows} rows, ${text.length} characters, ${changed}`)
  } catch (error) {
    console.error(
      `build-rankings: ${error instanceof Error ? error.message : error} — the committed payload is untouched`,
    )
    process.exitCode = 1
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await main()
}
