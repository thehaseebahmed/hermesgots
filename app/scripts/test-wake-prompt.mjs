/**
 * A wake run's input is the model's, never the user's: the row the plugin posts when a subagent
 * finishes opens with the pinned header, and the thread draws nothing of it — while the delivery
 * Hermes writes for the same finish still draws as the bot's own message, and a transcript from
 * before wakes existed reads exactly as it did. Pure over the rows, so a synced, reloaded or
 * imported chat folds it the same way.
 */
import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import test from "node:test"

import { isSubagentResult, subagentResults } from "../src/lib/subagent-results.ts"
import { isWakePrompt, WAKE_PROMPT_FOOTER, WAKE_PROMPT_HEADER } from "../src/lib/wake-prompt.ts"

/** A child session id: what the header names, never a compression continuation's. */
const CHILD = "0f3a9c1e-2b7d-4a55-9f1c-8e6a0d3b5c72"
const GOAL = "Review the parser for the reader"
const RESULT = "The parser reads a reply in parse.ts, then keeps its blocks."

/**
 * The wake run's input, line for line as the plugin composes it (`plugin/delegation.py`, pinned by
 * `plugin/tests/test_delegation_wake.py`): the header, the paragraph for the model, the facts, the
 * result, and core's footer.
 */
const WAKE = [
  `[ASYNC DELEGATION COMPLETE — ${CHILD}]`,
  "A background subagent you dispatched earlier has finished. You may have moved on since dispatching",
  "it; the full task source is below so you can act on the result or re-dispatch if things have changed.",
  "",
  "Dispatched: 2026-10-23 12:04:11 (4m ago)",
  `Original goal: ${GOAL}`,
  "Model: anthropic/claude-sonnet-4",
  "Status: completed   API calls: 7   Duration: 214s",
  "--- RESULT ---",
  RESULT,
  "",
  "[INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user. Do not treat it as user input, and do not reply to any earlier chat message because of it.]",
].join("\n")

/** The wake run's input row: an ordinary `user` row, with no display kind at all. */
const wake = (id, content = WAKE) => ({ id, role: "user", content, timestamp: 1_700_000_000 })

/** The visible row core writes for the same finish: the same header, drawn as the bot's message. */
const delivery = (id) => ({
  id,
  role: "user",
  display_kind: "async_delegation_complete",
  content: WAKE,
  timestamp: 1_700_000_001,
})

test("the wake run's input is not the user's message", () => {
  assert.equal(
    WAKE_PROMPT_HEADER,
    "[ASYNC DELEGATION COMPLETE — ",
    "the pinned header, em dash and all",
  )
  assert.equal(
    WAKE_PROMPT_FOOTER,
    "[INTERNAL NOTIFICATION — generated by the Hermes gateway",
    "core's footer, which closes every wake",
  )
  assert.equal(isWakePrompt(wake(1)), true, "the row the plugin posts draws nothing of its own")
})

test("the delivery row of the same finish stays the bot's message", () => {
  const row = delivery(2)
  assert.equal(isWakePrompt(row), false, "a delivery is never the wake prompt")
  assert.equal(isSubagentResult(row), true, "and it is still drawn as the bot's own message")
  assert.deepEqual([...subagentResults([row]).keys()], [2], "with the result it carries")
})

test("a user who types the wake's header keeps their own message", () => {
  // The header alone is a shape anyone can write, so the row needs both markers the plugin posts:
  // the header and core's footer. A message carrying only the first draws as the user's, always.
  const typed = `[ASYNC DELEGATION COMPLETE — ${CHILD}] what does this even mean?`
  assert.equal(isWakePrompt(wake(1, typed)), false, "a typed header draws as the user's message")
  assert.equal(
    isWakePrompt(wake(2, WAKE.split("\n").slice(0, -1).join("\n"))),
    false,
    "the plugin's own text with the footer cut off is not a wake either",
  )
  assert.equal(isWakePrompt(wake(3)), true, "while the whole shape is")
})

test("a wake prompt is the header on line 1 and the footer under it", () => {
  const rows = [
    // Another notification's header, with the footer the plugin always appends.
    wake(1, ["[ASYNC DELEGATION BATCH COMPLETE — d-3-2]", RESULT, "", WAKE_PROMPT_FOOTER + "]"].join("\n")),
    wake(2, ["[ASYNC DELEGATION TASK FAILED — d-4, task 1/2]", RESULT, "", WAKE_PROMPT_FOOTER + "]"].join("\n")),
    // The header, but not on line 1.
    wake(3, ["Not a wake: ", `[ASYNC DELEGATION COMPLETE — d-1]`, RESULT, "", WAKE_PROMPT_FOOTER + "]"].join("\n")),
    // Its bracket left open.
    wake(4, `[ASYNC DELEGATION COMPLETE — d-1\n${RESULT}\n\n${WAKE_PROMPT_FOOTER}]`),
    wake(5, "Where did the parser read a reply?"),
    wake(6, WAKE.replace("COMPLETE", "COMPLETED")),
  ]
  assert.deepEqual(rows.map(isWakePrompt), [false, false, false, false, false, false])
})

test("only a user row with no display kind is a wake prompt", () => {
  assert.equal(isWakePrompt({ ...wake(1), role: "assistant" }), false, "the bot's own words")
  assert.equal(isWakePrompt({ ...wake(1), role: "tool" }), false, "a tool's result")
  assert.equal(
    isWakePrompt({ ...wake(1), display_kind: "hidden" }),
    false,
    "a row the thread hides",
  )
  assert.equal(
    isWakePrompt({ ...wake(1), display_kind: "steer" }),
    false,
    "a message handed mid-turn",
  )
  assert.equal(isWakePrompt({ ...wake(1), content: null }), false, "a row with no text at all")
})

test("a wake prompt never reaches the subagent results", () => {
  const rows = [wake(1), delivery(2)]
  const found = subagentResults(rows)
  assert.deepEqual([...found.keys()], [2], "the delivery only: the wake prompt is no result")
})

test("a transcript from before wakes existed folds as it did", () => {
  const rows = [
    { id: 1, role: "user", content: "Where does the parser read a reply?", timestamp: 1 },
    { id: 2, role: "assistant", content: RESULT, timestamp: 2 },
    { id: 3, role: "user", content: "Thanks!", timestamp: 3 },
  ]
  assert.deepEqual(rows.map(isWakePrompt), [false, false, false], "nothing claims to be a wake")
})

/**
 * The pinned line-1 prefix is authored three times — by the plugin that posts the wake, by this app
 * that folds on it, and by the mock the e2e flows run against — and drift between them is silent:
 * a wake the app no longer recognises draws as the user's own message. So each file is read here
 * as it stands, and their literals are held to one another.
 */
const pluginSource = readFileSync(new URL("../../plugin/delegation.py", import.meta.url), "utf8")
const mockSource = readFileSync(new URL("./mock-hermes.mjs", import.meta.url), "utf8")

test("the plugin, the app and the mock post one header", () => {
  const template = pluginSource.match(/^WAKE_HEADER = "(\[ASYNC DELEGATION COMPLETE [^"]*)"/m)?.[1]
  assert.ok(template, "plugin/delegation.py states a WAKE_HEADER this test can read")
  const posted = template.replace("{subagent_id}", CHILD)

  const written = mockSource.match(/`(\[ASYNC DELEGATION COMPLETE [^`]*)\$\{child\.id\}\]`/)?.[1]
  assert.ok(written, "scripts/mock-hermes.mjs writes a delegation notice this test can read")
  const mocked = `${written}${CHILD}]`

  assert.equal(posted, mocked, "the mock posts the plugin's own header")
  assert.equal(
    posted,
    WAKE_PROMPT_HEADER + CHILD + "]",
    "the app folds on exactly the prefix the plugin writes",
  )
})

/**
 * The footer is the other half of the shape `isWakePrompt` asks for, so it is held to the same
 * cross-check: the app, the plugin that appends it and the mock that mimics both.
 */
test("the plugin, the app and the mock append one footer", () => {
  assert.ok(
    pluginSource.includes(`"${WAKE_PROMPT_FOOTER}`),
    "plugin/delegation.py states the footer this app folds on",
  )
  assert.ok(
    mockSource.includes(`"${WAKE_PROMPT_FOOTER}`),
    "scripts/mock-hermes.mjs appends the plugin's own footer",
  )
})
