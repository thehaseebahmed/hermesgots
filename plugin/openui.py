"""The interface library, told to the model as system-prompt sections, behind the profile's switch.

Two sections from two libraries (ADR 0101): ``prompt.txt`` is the chat's and ``app-prompt.txt`` the
app's, each answering only for sessions of its own kind — an app run is a session ``mark_app_run``
marked at its start. Both artifacts are beside this module, generated by
``app/scripts/build-openui-prompt.mjs`` and drift-tested by the app. Hermes freezes a section at
session start, and off answers it with nothing, so the next chat isn't told the library.
"""

from __future__ import annotations

import logging
import re
from pathlib import Path
from typing import Any, Dict, Mapping, Optional

logger = logging.getLogger(__name__)

FEATURE = "openui"
SECTION = "openui"
POSITION = "after_memory"
# The key the switch is kept under in the profile's `host_settings` (store.py). Absent means on, so
# only an off ever writes a row.
SETTING = "openui"
OBJECT = "gots.openui"

# The app's own section and the feature its registration advertises: a host whose plugin predates
# it answers no `apps`, and the app reads that as "this bot cannot make apps" (ADR 0101).
APP_FEATURE = "apps"
APP_SECTION = "apps"

# The key a marked app run is kept under in the profile's store, one row per session. A session
# nothing marks is a chat's — which is every session until a build run marks itself.
APP_RUN = "app-run"

# `plugin/openui.py` and the `plugin/openui/` folder coexist on purpose: the module wins the import
# and the artifact folder is its sibling. Never `importlib.resources`, which would look inside a
# package that isn't one.
ARTIFACT = Path(__file__).parent / "openui" / "prompt.txt"
APP_ARTIFACT = Path(__file__).parent / "openui" / "app-prompt.txt"
# The artifact's first line: the library the words were generated from, and the version that parses
# them. Read from the text, so there is one version source and no sidecar file to fall behind.
_HEADER = re.compile(r"^# @openuidev/react-lang (\S+)\s*$", re.M)

# Hermes's DEFAULT_SYSTEM_PROMPT_SECTION_MAX_CHARS, and the cap the generator writes under. A
# section past it is dropped whole at render, so registering one would advertise a vocabulary the
# model is never told. The sections also share MAX_SYSTEM_PROMPT_SECTIONS_TOTAL_CHARS (8_000): the
# chat's spends 3_848 and the app's 3_283 the last time they were measured, and a session carries
# only one of the two (each answers with nothing for the other's kind), with the routines section's
# 397 the only constant beside either.
LIMIT = 4_000


def _read(artifact: Path) -> str:
    """An artifact's words, or "" when it can't be read: a missing file must not break the plugin."""
    try:
        return artifact.read_text(encoding="utf-8")
    except OSError:
        logger.warning("gots: couldn't read the %s artifact", artifact.name, exc_info=True)
        return ""


def _version(text: str) -> Optional[str]:
    match = _HEADER.search(text)
    return match.group(1) if match else None


TEXT = _read(ARTIFACT)
VERSION = _version(TEXT)
APP_TEXT = _read(APP_ARTIFACT)
APP_VERSION = _version(APP_TEXT)

# Why the section isn't registered: `advertised` reports nothing, so `info` claims nothing.
_refusal_reason: Optional[str] = "The openui section isn't registered."
_app_refusal_reason: Optional[str] = "The app section isn't registered."


def _session_field(session: Optional[Mapping[str, Any]], name: str) -> Optional[str]:
    """A string off the session mapping, or None where it doesn't say (or isn't a mapping)."""
    try:
        value = (session or {}).get(name)
    except AttributeError:
        return None
    return value if isinstance(value, str) and value else None


def _profile(session: Optional[Mapping[str, Any]]) -> Optional[str]:
    """The profile a session runs as, as Hermes hands it to a section: None when it doesn't say."""
    return _session_field(session, "profile_name")


def path_for(profile_name: Optional[str] = None) -> Optional[Path]:
    """The store holding that profile's switch, or None when the profile's home can't be worked out.

    The section is rendered where a thread may have lost the ambient ``HERMES_HOME``, so the profile
    the session names is the one asked for its home; with no name, this process's own home is right.
    """
    try:
        if profile_name:
            from hermes_cli.profiles import get_profile_dir

            home = Path(get_profile_dir(profile_name))
        else:
            from hermes_constants import get_hermes_home

            home = Path(get_hermes_home())
        # Imported here: `plugin/openui.py` is also loaded by file path in a test, where the package
        # its relative imports need isn't there, and a missing store must not break the import.
        from .store import db_path
    except Exception:
        logger.debug("gots: couldn't resolve the openui switch's profile", exc_info=True)
        return None
    return db_path(home)


def enabled(path: Optional[Path]) -> bool:
    """The switch as the host holds it: on unless a stored value says off.

    A store that can't be read leaves it on, the way a failed read fails open everywhere else here:
    a host that can't answer must not take the library away from every new chat.
    """
    if path is None:
        return True
    try:
        from .store import get_setting

        value = get_setting(path, SETTING)
    except Exception:
        logger.debug("gots: couldn't read the openui switch", exc_info=True)
        return True
    return True if value is None else bool(value)


def set_enabled(path: Path, value: bool) -> bool:
    """Stores the switch and answers what the store now holds.

    ``put_setting(path, key, None)`` deletes the row, so off is written as the boolean it is: a
    missing row reads as on, and an off kept as None would come back as the default.
    """
    from .store import put_setting

    put_setting(path, SETTING, bool(value))
    return enabled(path)


def record(value: bool) -> Dict[str, Any]:
    """The route pair's answer: the switch, and the library version the section was generated from."""
    return {"object": OBJECT, "enabled": bool(value), "version": VERSION}


def mark_app_run(session_id: str, profile_name: Optional[str] = None) -> bool:
    """Marks a session as one an app's build or change runs in.

    The seam the build flow starts from (#858): a session nothing marks is a chat's, and the two
    sections divide the kinds between them, so a chat pays for none of the app's vocabulary and an
    app run for none of the chat's (ADR 0101). The mark lives only while the session does — see
    `unmark_app_run`.
    """
    if not isinstance(session_id, str) or not session_id:
        return False
    path = path_for(profile_name)
    if path is None:
        return False
    try:
        from .store import put_setting

        put_setting(path, f"{APP_RUN}:{session_id}", True)
    except Exception:
        logger.debug("gots: couldn't mark an app run", exc_info=True)
        return False
    return True


def unmark_app_run(session_id: Any, profile_name: Optional[str] = None) -> None:
    """Forgets a session's app-run mark once the session is done.

    The prompt is frozen at session start and restored from those bytes on resume, so a finished
    session has no reader left: without this the row would outlive every run it named, one per
    build, in the profile's store, for ever. A session that never fires its end keeps its row.
    """
    if not isinstance(session_id, str) or not session_id:
        return
    path = path_for(profile_name)
    if path is None:
        return
    try:
        from .store import put_setting

        put_setting(path, f"{APP_RUN}:{session_id}", None)
    except Exception:
        logger.debug("gots: couldn't clear an app run's mark", exc_info=True)


def is_app_run(session: Optional[Mapping[str, Any]], path: Optional[Path]) -> bool:
    """Whether a session is an app run's, as the sections divide them.

    `path` is the profile's store, as the caller resolved it: a section resolves its profile's home
    once and reads every question against that one path.
    """
    session_id = _session_field(session, "session_id")
    if session_id is None or path is None:
        return False
    try:
        from .store import get_setting

        return get_setting(path, f"{APP_RUN}:{session_id}") is True
    except Exception:
        logger.debug("gots: couldn't read an app run's mark", exc_info=True)
        return False


def _section_text(text: str, session: Optional[Mapping[str, Any]], app: bool) -> str:
    """One section's answer for a session: the switch and the kind each withhold with "".

    `app` is whose rules these are, so one ladder decides both sections and neither can drift from
    the other's gates.
    """
    if not text:
        return ""
    path = path_for(_profile(session))
    if not enabled(path):
        return ""
    if is_app_run(session, path) != app:
        return ""
    return text


def content(session: Optional[Mapping[str, Any]] = None) -> str:
    """The chat's section for a session, which Hermes renders once and freezes into its prompt.

    While the switch is off this is "": an empty section is the only way to withhold one, and the
    host drops it silently, so the chat being started is told nothing about the library. A chat
    already open keeps the prompt it was started with, since Hermes never rewrites one. An app
    run's session gets none of this — its own section is all it pays for.
    """
    return _section_text(TEXT, session, False)


def app_content(session: Optional[Mapping[str, Any]] = None) -> str:
    """The app's section for a session: the same library in its own words (ADR 0101).

    Answers with nothing for any session that isn't an app run — the rules are about a page, and a
    reply has no page to be about.
    """
    return _section_text(APP_TEXT, session, True)


def _register(
    ctx: Any, section_id: str, text: str, version: Optional[str], content_fn: Any, what: str
) -> Optional[str]:
    """Registers one section and answers why it couldn't, or None where it took.

    This Hermes may predate `register_system_prompt_section` (the plugin ships ahead of the host it
    runs on), and the call raises for anything it doesn't like, so it is guarded: a raise here
    would take every route of the plugin down with it.
    """
    register_section = getattr(ctx, "register_system_prompt_section", None)
    if not callable(register_section):
        return "This Hermes can't add a system-prompt section."
    if not text or version is None:
        return f"The {what} prompt artifact didn't load."
    if len(text) > LIMIT:
        return f"The {what} prompt artifact is over the host's section limit."
    try:
        register_section(section_id, content_fn, position=POSITION)
    except Exception:
        logger.warning("gots: couldn't register the %s section", what, exc_info=True)
        return f"This Hermes refused the {what} section."
    return None


def register(ctx: Any) -> bool:
    """Registers the chat's section with this Hermes, or leaves the plugin running without it."""
    global _refusal_reason
    _refusal_reason = _register(ctx, SECTION, TEXT, VERSION, content, "openui")
    if _refusal_reason is None:
        logger.info("gots: telling the model the component library (%s)", VERSION)
    return _refusal_reason is None


def app_register(ctx: Any) -> bool:
    """Registers the app's section beside the chat's — the feature `apps` stands for."""
    global _app_refusal_reason
    _app_refusal_reason = _register(ctx, APP_SECTION, APP_TEXT, APP_VERSION, app_content, "app")
    if _app_refusal_reason is None:
        logger.info("gots: telling an app run its own rules (%s)", APP_VERSION)
    return _app_refusal_reason is None


def advertised() -> Optional[Dict[str, str]]:
    """The sibling object `info` carries beside the bare feature, or None where there is none."""
    return None if _refusal_reason is not None else {"version": VERSION}


def app_advertised() -> Optional[Dict[str, str]]:
    """That answer for `apps`: the library version an app's record is stamped with, or None."""
    return None if _app_refusal_reason is not None else {"version": APP_VERSION}
