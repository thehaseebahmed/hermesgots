class Registry:
    """Core's live-subagent registry, which a stop goes through."""

    def __init__(self) -> None:
        self.stopped: List[str] = []
        self.live: List[str] = ["sa-1"]
        # ``tools.delegate_tool_registry``'s own table of live children, keyed by core's id.
        self._active_subagents: Dict[str, Any] = {}

    def interrupt_subagent(self, agent_id: str) -> bool:
        self.stopped.append(agent_id)
        return agent_id in self.live


