        self.assertEqual(self.posted, [])
        # The answer lands; the next look wakes the bot with what it was waiting on.
        self.adapter._run_statuses.clear()
        self.assertEqual(self.sweep(), 1)
        self.assertEqual(len(self.posted), 1)

