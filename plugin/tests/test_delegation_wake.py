"""Waking a bot when its subagent finishes, and stopping one from its card.

A subagent's result re-enters the conversation as its own row (core writes it), but nothing told the
bot: on a keyed ``/v1/runs`` session the agent is not woken, so the result waited for the user to
write again. The plugin now posts an ordinary run on the conversation itself — through the loopback
outbox, the route queued messages and AFK already use — carrying the child's result, so the bot reads
it in a new turn.

What is pinned here is only what the plugin does to the outside: the run it posts (its path, body and
idempotency key), when it does not post (a question or an approval pending, a turn still running, a
child still running), the mark that keeps a restart from posting twice, and the stop route's answers —
including that a stop really asks core to interrupt the child, rather than only marking its row.

Everything about the child's transcript is read from a real ``state.db`` the harness writes; core's
live-subagent registry, which a stop goes through, is planted in ``sys.modules`` (the suite's second
harness trap), since a test machine has no /opt/data/hermes-agent.

Run: python3 -m unittest plugin.tests.test_delegation_wake -v
"""

from __future__ import annotations

import asyncio
import json
import sqlite3
import sys
import tempfile
import time
import unittest
from pathlib import Path
from types import ModuleType
from typing import Any, Dict, List, Optional
from unittest import mock

import plugin
from plugin import delegation, outbox, sessions
from plugin.tests._helpers import App, Context, FakeWeb, Router
from plugin.store import db_path

# Core's own machine-provenance footer (gateway/run_notifications.py `INTERNAL_NOTIFICATION_FOOTER`),
# spelled here so the test disagrees with the plugin if either text moves.
FOOTER = (
    "[INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user. "
    "Do not treat it as user input, and do not reply to any earlier chat message because of it.]"
)


class Adapter:
    """The API server, as far as a wake reaches it: its run statuses, and nothing else."""

    def __init__(self) -> None:
        self._run_statuses: Dict[str, Dict[str, Any]] = {}
        self._api_key = "process-key"
        self._check_auth = lambda request: None

    def run(self, run_id: str, session_id: str, status: str, **extra: Any) -> None:
        self._run_statuses[run_id] = {"run_id": run_id, "session_id": session_id, "status": status, **extra}


class WakeTest(unittest.TestCase):
    def setUp(self) -> None:
        self.tmp = tempfile.TemporaryDirectory()
        self.home = Path(self.tmp.name)
        self.addCleanup(self.tmp.cleanup)
        self.state = self.home / "state.db"
        self.conn = sqlite3.connect(self.state)
        self.addCleanup(self.conn.close)
        self.conn.execute(
            "CREATE TABLE sessions (id TEXT PRIMARY KEY, model TEXT, model_config TEXT,"
            " parent_session_id TEXT, started_at REAL, ended_at REAL, end_reason TEXT,"
            " tool_call_count INTEGER DEFAULT 0, api_call_count INTEGER DEFAULT 0, source TEXT)"
        )
        self.conn.execute(
            "CREATE TABLE messages (id INTEGER PRIMARY KEY AUTOINCREMENT, session_id TEXT, role TEXT,"
            " content TEXT, tool_calls TEXT, finish_reason TEXT)"
        )
        # Real clock time, as ``state.db`` has it: a watcher's watermark is a wall-clock stamp.
        self.clock = time.time()
        # The key a wake posts with, in the home's own .env, as AFK reads it.
        (self.home / ".env").write_text("API_SERVER_KEY=home-key\n", encoding="utf-8")
        self.adapter = Adapter()
        self.posted: List[Dict[str, Any]] = []
        self.fail = False
        # What the host answers a post with; None is the ordinary ``{"run_id": …}``.
        self.answer: Optional[Dict[str, Any]] = None
        self.plant_post()

    def plant_post(self) -> None:
        async def post(adapter, profile, path, body, authorization=None, idempotency_key=None):
            self.posted.append(
                {
                    "profile": profile,
                    "path": path,
                    "body": body,
                    "authorization": authorization,
                    "key": idempotency_key,
                }
            )
            if self.fail:
                raise outbox.StartError("the host refused it", False)
            return dict(self.answer) if self.answer is not None else {"run_id": f"run-{len(self.posted)}"}

        wiring = mock.patch.object(outbox, "post", new=post)
        wiring.start()
        self.addCleanup(wiring.stop)

    def chat(self, session_id: str, *, parent: Optional[str] = None, reason: Optional[str] = None,
             source: str = "api_server") -> None:
        """A conversation in Hermes's store: it has no delegation marker of its own."""
        self.clock += 1
        self.conn.execute(
            "INSERT INTO sessions (id, model, model_config, parent_session_id, started_at, ended_at,"
            " end_reason, tool_call_count, source) VALUES (?, 'm', NULL, ?, ?, ?, ?, 0, ?)",
            (session_id, parent, self.clock, self.clock if reason else None, reason, source),
        )
        self.conn.commit()

    def child(self, session_id: str, parent: str, *, goal: Optional[str] = None,
              said: Optional[str] = None, ended: bool = True, reason: str = "agent_close",
              calls: int = 0, model: str = "anthropic/claude-sonnet-4", finish: Optional[str] = None,
              trailing: Optional[str] = None, delegate_from: Optional[str] = None) -> None:
        """A session the conversation delegated to, as Hermes keeps it."""
        self.clock += 1
        config = json.dumps({"_delegate_from": delegate_from or parent})
        self.conn.execute(
            "INSERT INTO sessions (id, model, model_config, parent_session_id, started_at, ended_at,"
            " end_reason, tool_call_count, source) VALUES (?, ?, ?, ?, ?, ?, ?, ?, 'subagent')",
            (session_id, model, config, parent, self.clock, self.clock + 9 if ended else None,
             reason if ended else None, calls),
        )
        if goal:
            self.said(session_id, "user", goal)
        if said:
            self.said(session_id, "assistant", said, finish=finish)
        if trailing:
            self.said(session_id, "tool", trailing)
        self.conn.commit()

    def said(self, session_id: str, role: str, content: str, *, finish: Optional[str] = None,
             tool_calls: Optional[str] = None) -> None:
        self.conn.execute(
            "INSERT INTO messages (session_id, role, content, tool_calls, finish_reason)"
            " VALUES (?, ?, ?, ?, ?)",
            (session_id, role, content, tool_calls, finish),
        )

    def sweep(self) -> int:
        return asyncio.run(delegation.sweep(self.adapter, self.home))

    def text(self, index: int = 0) -> str:
        return self.posted[index]["body"]["input"][0]["content"]

    def test_a_finished_subagent_wakes_its_bot(self) -> None:
        self.chat("s")
        self.child("c1", "s", goal="review the auth diff", said="The refactor is safe; two nits.",
                   calls=7)
        self.assertEqual(self.sweep(), 1)
        (posted,) = self.posted
        self.assertEqual(posted["path"], "/v1/runs")
        self.assertEqual(posted["key"], "wake_c1")
        self.assertEqual(posted["authorization"], "Bearer home-key")
        self.assertEqual(posted["body"]["session_id"], "s")
        self.assertEqual(posted["body"]["input"][0]["role"], "user")
        text = self.text()
        self.assertEqual(text.splitlines()[0], "[ASYNC DELEGATION COMPLETE — c1]")
        self.assertIn("Original goal: review the auth diff", text)
        self.assertIn("The refactor is safe; two nits.", text)
        self.assertIn("Status: completed", text)
        self.assertTrue(text.endswith(FOOTER))
        # The mark is written after the post, so the next look — or a restarted plugin — sees it.
        self.assertEqual(sessions.marked_wakes(db_path(self.home), ["c1"]), {"c1"})

    def test_a_wake_is_posted_once(self) -> None:
        self.chat("s")
        self.child("c1", "s", said="done")
        self.assertEqual(self.sweep(), 1)
        self.assertEqual(self.sweep(), 0)
        self.assertEqual(len(self.posted), 1)

    def test_a_wake_posted_before_a_restart_is_not_posted_again(self) -> None:
        """What keeps a restart from doubling is the store's mark, not this process's memory."""
        self.chat("s")
        self.child("c1", "s", said="done")
        sessions.mark_wake(db_path(self.home), "c1", "s", "run-from-before")
        self.assertEqual(self.sweep(), 0)
        self.assertEqual(self.posted, [])

    def test_no_wake_while_the_user_is_being_asked(self) -> None:
        self.chat("s")
        self.child("c1", "s", said="done")
        # The bot asked a question in the turn that started this subagent. Core refuses to let a
        # completion cross that gate, and so does the wake: it waits for the answer.
        self.adapter.run(
            "run-1", "s", "waiting_for_approval",
            clarify={"clarify_id": "q", "questions": [{"id": "q0", "question": "Which branch?"}]},
        )
        self.assertEqual(self.sweep(), 0)
        self.assertEqual(self.posted, [])
        # The answer lands; the next look wakes the bot with what it was waiting on.
        self.adapter._run_statuses.clear()
        self.assertEqual(self.sweep(), 1)
        self.assertEqual(len(self.posted), 1)

    def test_no_wake_while_an_approval_waits(self) -> None:
        self.chat("s")
        self.child("c1", "s", said="done")
        self.adapter.run(
            "run-1", "s", "waiting_for_approval", approval={"command": "rm -rf build"},
        )
        self.assertEqual(self.sweep(), 0)
        self.adapter._run_statuses.clear()
        self.assertEqual(self.sweep(), 1)

    def test_no_wake_while_the_turn_that_delegated_is_running(self) -> None:
        self.chat("s")
        self.child("c1", "s", said="done")
        self.adapter.run("run-1", "s", "running")
        self.assertEqual(self.sweep(), 0)
        self.assertEqual(self.posted, [])
        self.adapter.run("run-1", "s", "completed")
        self.assertEqual(self.sweep(), 1)

    def test_a_post_that_failed_is_tried_again(self) -> None:
        self.chat("s")
        self.child("c1", "s", said="done")
        self.fail = True
        self.assertEqual(self.sweep(), 0)
        self.assertEqual(sessions.marked_wakes(db_path(self.home), ["c1"]), set())
        self.fail = False
        self.assertEqual(self.sweep(), 1)
        self.assertEqual(len(self.posted), 2)
        # The same key both times, so a run the host did start answers itself rather than doubling.
        self.assertEqual([post["key"] for post in self.posted], ["wake_c1", "wake_c1"])

    def test_a_post_the_host_answered_without_a_run_is_not_a_wake(self) -> None:
        self.chat("s")
        self.child("c1", "s", said="done")
        self.answer = {"error": "not really"}
        self.assertEqual(self.sweep(), 0)
        self.assertEqual(sessions.marked_wakes(db_path(self.home), ["c1"]), set())
        self.answer = None
        self.assertEqual(self.sweep(), 1)

    def test_a_failed_subagent_still_wakes_with_its_reason(self) -> None:
        self.chat("s")
        self.child(
            "c1", "s", goal="patch the flaky test", said="I couldn't reach the sandbox.",
            reason="cancelled", finish="error",
        )
        self.assertEqual(self.sweep(), 1)
        text = self.text()
        self.assertEqual(text.splitlines()[0], "[ASYNC DELEGATION COMPLETE — c1]")
        self.assertIn("Status: error", text)
        self.assertIn("The subagent did not complete successfully (status=error).", text)
        self.assertIn("End reason: cancelled", text)
        self.assertIn("Partial output:", text)
        self.assertIn("I couldn't reach the sandbox.", text)
        self.assertTrue(text.endswith(FOOTER))

    def test_a_stopped_subagent_wakes_as_interrupted(self) -> None:
        self.chat("s")
        self.child("c1", "s", goal="build it", said="Partway through.", trailing='[{"name": "shell"}]')
        self.assertEqual(self.sweep(), 1)
        text = self.text()
        self.assertIn("Status: interrupted", text)
        self.assertIn("The subagent did not complete successfully (status=interrupted).", text)

    def test_a_subagent_still_running_is_not_woken(self) -> None:
        self.chat("s")
        self.child("c1", "s", said="half of it", ended=False)
        self.assertEqual(self.sweep(), 0)
        self.assertEqual(self.posted, [])

    def test_a_compressed_subagent_wakes_from_its_continuation(self) -> None:
        self.chat("s")
        self.child("c1", "s", goal="read the diff", ended=True, reason="compression")
        # Compression copies the delegation marker down, so the continuation is not a delegation of
        # its own stream — the child's own row walks to it instead.
        self.child("c1b", "c1", delegate_from="s", ended=False)
        self.assertEqual(self.sweep(), 0, "a child whose continuation still runs hasn't ended")
        self.conn.execute(
            "UPDATE sessions SET ended_at = 99, end_reason = 'agent_close' WHERE id = 'c1b'"
        )
        self.said("c1b", "assistant", "The diff has two real changes.")
        self.conn.commit()
        self.assertEqual(self.sweep(), 1)
        self.assertIn("The diff has two real changes.", self.text())
        # Marked against the child the app knows, not the continuation it ended on.
        self.assertEqual(self.posted[0]["key"], "wake_c1")
        self.assertEqual(sessions.marked_wakes(db_path(self.home), ["c1", "c1b"]), {"c1"})

    def test_a_subagent_that_ended_before_the_plugin_watched_is_left_alone(self) -> None:
        """A home carries every subagent it ever ran; the first look must not wake all of them."""
        self.chat("s")
        self.child("c1", "s", said="from last week")
        self.conn.execute("UPDATE sessions SET ended_at = ? WHERE id = 'c1'", (time.time() - 86_400,))
        self.conn.commit()
        self.assertEqual(self.sweep(), 0)
        self.assertEqual(self.posted, [])
        self.assertEqual(sessions.marked_wakes(db_path(self.home), ["c1"]), set())
        # One that ends after the watch began is woken.
        self.child("c2", "s", said="from just now")
        self.assertEqual(self.sweep(), 1)
        self.assertEqual([post["key"] for post in self.posted], ["wake_c2"])

    def test_two_subagents_finishing_together_get_one_wake_each(self) -> None:
        self.chat("s")
        self.child("c1", "s", said="the first one's work")
        self.child("c2", "s", said="the second one's work")
        self.assertEqual(self.sweep(), 2)
        self.assertEqual(sorted(post["key"] for post in self.posted), ["wake_c1", "wake_c2"])
        self.assertEqual(sessions.marked_wakes(db_path(self.home), ["c1", "c2"]), {"c1", "c2"})

    def test_the_wake_goes_on_the_chat_a_compression_moved_on(self) -> None:
        """The child hangs off the live tip; the run has to name the chat the app knows."""
        self.chat("s", reason="compression")
        self.chat("s2", parent="s")
        self.child("c1", "s2", said="after the compression")
        self.assertEqual(self.sweep(), 1)
        self.assertEqual(self.posted[0]["body"]["session_id"], "s")


class Registry:
    """Core's live-subagent registry, which a stop goes through."""

    def __init__(self) -> None:
        self.stopped: List[str] = []
        self.live: List[str] = ["sa-1"]
        # ``tools.delegate_tool_registry``'s own table of live children, keyed by core's id.
        self._active_subagents: Dict[str, Any] = {}

    def interrupt_subagent(self, agent_id: str) -> bool:
        self.stopped.append(agent_id)
        return agent_id in self.live


class RouteAdapter:
    """The API server: its auth check, and nothing else the stop route reaches."""

    def __init__(self) -> None:
        self.denied: Any = None

    def _check_auth(self, request: Any) -> Any:
        return self.denied


class StopRouteTest(unittest.TestCase):
    def setUp(self) -> None:
        self.tmp = tempfile.TemporaryDirectory()
        self.home = Path(self.tmp.name)
        self.addCleanup(self.tmp.cleanup)
        self.registry = Registry()
        registry = ModuleType("tools.delegate_tool_registry")
        registry.interrupt_subagent = self.registry.interrupt_subagent
        registry._active_subagents = self.registry._active_subagents
        constants = ModuleType("hermes_constants")
        constants.get_hermes_home = lambda: str(self.home)
        tools = ModuleType("tools")
        tools.delegate_tool_registry = registry
        aiohttp = ModuleType("aiohttp")
        aiohttp.web = FakeWeb()
        planted = {
            "tools": tools,
            "tools.delegate_tool_registry": registry,
            "hermes_constants": constants,
            "aiohttp": aiohttp,
            "aiohttp.web": aiohttp.web,
        }
        wiring = mock.patch.dict(sys.modules, planted)
        wiring.start()
        self.addCleanup(wiring.stop)
        held = getattr(sessions, "adapter", None)
        self.addCleanup(setattr, sessions, "adapter", held)

        self.app, self.adapter = App(), RouteAdapter()
        context = Context()
        plugin.register(context)
        context.platforms["api_server"](self.app, self.adapter)

    def route(self, path: str) -> Any:
        for _method, registered, handler in self.app.router.added:
            if registered == path:
                return handler
        raise AssertionError(f"the plugin registered no {path}")

    def stop(self, session_id: str, agent_id: str) -> Dict[str, Any]:
        handler = self.route(plugin.PREFIX + "/sessions/{session_id}/agents/{agent_id}/stop")
        request = FakeWeb.Request()
        request.match_info = {"session_id": session_id, "agent_id": agent_id}
        request.headers = {}
        return asyncio.run(handler(request))

    def test_stop_asks_core_to_interrupt_that_subagent(self) -> None:
        # The id the app has is the child's session id; core's registry is keyed by its own.
        sessions.remember_agent(db_path(self.home), "c1", "sa-1")
        answer = self.stop("s", "c1")
        self.assertEqual(answer["status"], 200)
        self.assertEqual(answer["payload"]["object"], "memento.agent_stop")
        self.assertEqual(answer["payload"]["session_id"], "s")
        self.assertEqual(answer["payload"]["agent_id"], "c1")
        self.assertTrue(answer["payload"]["stopped"])
        self.assertEqual(self.registry.stopped, ["sa-1"], "the child's work wasn't actually stopped")

    def test_stop_finds_a_child_this_plugin_never_saw_start(self) -> None:
        class Live:
            session_id = "c1"

        self.registry._active_subagents["sa-9"] = {"agent": Live()}
        self.registry.live.append("sa-9")
        answer = self.stop("s", "c1")
        self.assertTrue(answer["payload"]["stopped"])
        self.assertEqual(self.registry.stopped, ["sa-9"])

    def test_stop_of_a_child_that_has_finished_says_so_without_a_404(self) -> None:
        answer = self.stop("gone", "nope")
        self.assertEqual(answer["status"], 200)
        self.assertFalse(answer["payload"]["stopped"])
        self.assertEqual(answer["payload"]["reason"], "That subagent isn't running any more.")

    def test_stop_a_subagent_needs_the_bots_key(self) -> None:
        self.adapter.denied = {"status": 401, "payload": {}}
        self.assertEqual(self.stop("s", "c1"), {"status": 401, "payload": {}})
        self.assertEqual(self.registry.stopped, [])

    def test_the_start_hook_keeps_a_subagents_core_id(self) -> None:
        delegation.started(parent_session_id="s", child_session_id="c1", child_subagent_id="sa-7")
        self.assertEqual(sessions.agent_for(db_path(self.home), "c1"), "sa-7")

    def test_info_advertises_stopping_a_subagent(self) -> None:
        info = self.route(plugin.PREFIX + "/info")
        request = FakeWeb.Request()
        request.match_info, request.headers = {}, {}
        answer = asyncio.run(info(request))
        self.assertEqual(answer["status"], 200)
        self.assertIn("subagent_stop", answer["payload"]["features"])


if __name__ == "__main__":
    unittest.main()
