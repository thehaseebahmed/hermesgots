"""Whether this host can check a canvas's draft, and the check itself (ADR 0171).

A canvas's write was checked by ``scan`` and ``warnings`` and nothing ran the page. A build's draft
is now rendered by the plugin through Hermes's own browser backend, inside the harness page the
app's own frame code is bundled into (``plugin/canvas/harness.html``, generated by
``app/scripts/build-canvas-harness.mjs``), and its tests are run in it against a read-only snapshot
of the canvas's data. The runner answers pass or fail per test, the console's errors, and a
screenshot at 390px and 768px in the reader's light and dark mode.

``available`` is the probe: a host with no browser layer publishes a build unchecked rather than
failing to build, so a check that cannot run answers the reason instead of raising. The browser's
own side — a Chromium drawing the harness page — is the one thing a plugin test cannot run, so the
tests plant a layer that answers the runner's program the way the layer does.

Run: python3 -m unittest plugin.tests.test_canvas_checks -v
"""

from __future__ import annotations

import json
import logging
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Callable, Dict, List, Optional

logger = logging.getLogger(__name__)

NO_ENTRY = "This Hermes has no browser layer a plugin can call. Update Hermes."
NO_ENGINE = "Hermes's browser engine is missing from its Python environment. Run `hermes update`."
UNREADABLE = "This Hermes's browser layer couldn't be read. Update Hermes."
NO_HARNESS = "This Gots plugin carries no canvas check harness. Update the plugin."
NO_ANSWER = "Hermes's browser layer answered a check with something this plugin can't read."
REFUSED = "Hermes's browser layer refused the check."
FAILED = "Hermes's browser layer didn't finish the check."

# What a version published off a check says of it (GLOSSARY "Check flag"): passing where every
# test passed, failing where they still did after the build's rounds, and unchecked where the check
# never ran — a host with no browser, a plugin with no harness, a layer that refused.
PASSING = "passing"
FAILING = "failing"
UNCHECKED = "unchecked"

# The four drawings a check takes (G8): a phone and a tablet, in the reader's light and dark mode.
# The height is each device's own viewport, since a screenshot is of what a reader would see.
DRAWINGS = ((390, 844, "light"), (390, 844, "dark"), (768, 1024, "light"), (768, 1024, "dark"))

# The harness page a plugin is installed with, beside this module: the app's own frame document
# builder, its class compile and its library sources, as one self-contained page.
HARNESS = Path(__file__).resolve().parent / "canvas" / "harness.html"

# The name the harness page is opened under, so one host's checks share a browser session rather
# than each opening a tab of their own. Hermes's own rule for a session name: 1-64 of letters,
# digits, dashes or underscores.
SESSION = "gots-canvas-check"

# How long the whole of a check is given: four renders and four screenshots, on a slow host.
CHECK_TIMEOUT_S = 300


def available() -> Optional[str]:
    """Why this host can't run a canvas's checks, or None when it can.

    The import is inside the function, like every other Hermes module the plugin reaches: the
    module only exists on a Hermes host, and a test plants its own in ``sys.modules``.

    Two generations of Hermes can sit side by side on one install, and only one of them exports
    ``browser_exec_available``. Where it is absent the probe reads the engine check that wrapper
    calls (``_harness_site_dir``), so a layer that can draw isn't mistaken for one that isn't
    there; a layer exporting neither name is unreadable and answers not ready.
    """
    try:
        from tools import browser_use_cli
    except ImportError:
        return NO_ENTRY
    except Exception:
        logger.debug("gots: couldn't import Hermes's browser layer", exc_info=True)
        return UNREADABLE
    if not callable(getattr(browser_use_cli, "browser_exec", None)):
        return NO_ENTRY
    check = getattr(browser_use_cli, "browser_exec_available", None)
    if callable(check):
        try:
            ready = check()
        except Exception:
            logger.debug("gots: couldn't read Hermes's browser layer", exc_info=True)
            return UNREADABLE
        return None if ready else NO_ENGINE
    # Two generations of Hermes sit side by side on an install that keeps a release cache: the
    # running tree answers ``browser_exec`` but exports no availability wrapper, while the tree
    # beside it does. The wrapper only ever runs the engine's own import check, ``_harness_site_dir``,
    # so asking that directly reads the same fact on a tree with no wrapper — and the entry point
    # being callable is what says the layer is there at all. A tree exporting neither name is one
    # this plugin can't read, which is not the same as a host that can check: answer not ready.
    engine = getattr(browser_use_cli, "_harness_site_dir", None)
    if not callable(engine):
        return NO_ENTRY
    try:
        found = engine()
    except Exception:
        logger.debug("gots: couldn't read Hermes's browser engine", exc_info=True)
        return UNREADABLE
    return None if found else NO_ENGINE


def carried() -> Optional[str]:
    """Why this host has no harness page to draw a draft in, or None when it does."""
    return None if HARNESS.is_file() else NO_HARNESS


@dataclass
class Shot:
    """One screenshot a check took: the width and the mode it was drawn at, and where it landed."""

    width: int
    mode: str
    path: str


@dataclass
class CheckReport:
    """What a check answered: each test, the console's errors, the four screenshots.

    ``reason`` is why a check that couldn't run didn't — a host with no browser, a plugin with no
    harness, a layer that refused — and None where the page was drawn and checked.
    """

    tests: List[Dict[str, Any]] = field(default_factory=list)
    console: List[str] = field(default_factory=list)
    shots: List[Shot] = field(default_factory=list)
    reason: Optional[str] = None

    @property
    def ran(self) -> bool:
        return self.reason is None

    @property
    def passing(self) -> bool:
        """Whether every test passed: a check that didn't run has nothing to pass."""
        return self.ran and all(one.get("ok") for one in self.tests)

    @property
    def flag(self) -> str:
        """What a version published off this check says of it (GLOSSARY "Check flag").

        A check that never ran — no browser, no harness, a layer that refused — says ``unchecked``
        rather than claiming a pass it never made, and one that ran with a failing test says
        ``failing`` whether or not the build had another round left.
        """
        if not self.ran:
            return UNCHECKED
        return PASSING if self.passing else FAILING


def _program(request: Dict[str, Any], folder: Path) -> str:
    """The Python the browser layer runs: open the harness page, draw the draft four ways, shoot it.

    The request is handed to the page as the JSON the runner built it from, so the document, the
    snapshot and the tests are one literal in the program rather than four copies of a 256 KB page.
    The tests run in the first drawing — the plan's report answers one set of test results — and the
    other three are drawn only to be shot, which is what the empty test list asks the page for.
    """
    return "\n".join(
        [
            "# Draw a canvas draft the way the app draws it, run its tests and shoot it four ways",
            "import json",
            "",
            f"REQUEST = {json.dumps(request)}",
            "FOLDER = " + repr(str(folder)),
            "report = {'tests': [], 'console': [], 'shots': []}",
            "new_tab(" + repr(HARNESS.as_uri()) + ")",
            "wait_for_load()",
            "for width, height, mode in " + repr(DRAWINGS) + ":",
            '    cdp("Emulation.setDeviceMetricsOverride", width=width, height=height,',
            '        deviceScaleFactor=1, mobile=False)',
            '    cdp("Emulation.setEmulatedMedia", media="screen",',
            '        features=[{"name": "prefers-color-scheme", "value": mode}])',
            "    asked = dict(REQUEST, tests=REQUEST['tests'] if not report['shots'] else [])",
            '    answer = js("window.canvasHarness.check(%s, %s)" % (json.dumps(asked),',
            '        json.dumps(mode)))',
            "    if not report['shots']:",
            "        report['tests'] = answer.get('tests', [])",
            "        report['console'] = answer.get('console', [])",
            "    path = capture_screenshot(FOLDER + '/' + str(width) + '-' + mode + '.png')",
            "    report['shots'].append({'width': width, 'mode': mode, 'path': path})",
            'js("window.canvasHarness.close()")',
            "print(json.dumps(report))",
            "",
        ]
    )


def _read(answer: Any) -> Optional[Dict[str, Any]]:
    """The layer's answer as the object it is: ``browser_exec`` answers a JSON string."""
    if isinstance(answer, str):
        try:
            said = json.loads(answer)
        except ValueError:
            logger.debug("gots: the browser layer answered %r", answer[:200])
            return None
        return said if isinstance(said, dict) else None
    return answer if isinstance(answer, dict) else None


def _report_of(said: Dict[str, Any]) -> CheckReport:
    """The check the layer's answer describes, or the reason it gave for not describing one."""
    if "error" in said:
        return CheckReport(reason=str(said["error"]) or REFUSED)
    if not said.get("success"):
        return CheckReport(reason=FAILED)
    printed = str(said.get("output") or "").strip().splitlines()
    if not printed:
        return CheckReport(reason=NO_ANSWER)
    try:
        found = json.loads(printed[-1])
    except ValueError:
        logger.debug("gots: the check printed %r", printed[-1][:200])
        return CheckReport(reason=NO_ANSWER)
    return CheckReport(
        tests=found.get("tests", []),
        console=found.get("console", []),
        shots=[Shot(**one) for one in found.get("shots", [])],
    )


def _layer() -> Callable[..., Any]:
    """Hermes's own entry point, imported the way the plugin reaches every Hermes module."""
    from tools.browser_use_cli import browser_exec

    return browser_exec


def check(
    html: str,
    data: Dict[str, Any],
    tests: List[Dict[str, str]],
    folder: Path,
) -> CheckReport:
    """Draw a canvas's draft the way the app draws it, run its tests, and shoot it four ways.

    ``html`` is the whole document, ``data`` the read-only snapshot of the canvas's data the page is
    answered from, ``tests`` the scripts the build's plan filed, and ``folder`` where the four
    screenshots are written. A host with no browser layer, or a plugin with no harness, answers the
    reason and no screenshots: a build never stalls on its checks (ADR 0171).
    """
    reason = available() or carried()
    if reason:
        return CheckReport(reason=reason)
    folder = Path(folder)
    folder.mkdir(parents=True, exist_ok=True)
    request = {"html": html, "data": data, "tests": tests}
    try:
        answer = _layer()(_program(request, folder), session=SESSION, timeout_s=CHECK_TIMEOUT_S)
    except Exception:
        logger.debug("gots: Hermes's browser layer raised on a canvas check", exc_info=True)
        return CheckReport(reason=FAILED)
    said = _read(answer)
    return _report_of(said) if said is not None else CheckReport(reason=NO_ANSWER)
